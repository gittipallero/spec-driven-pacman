// LoadClassicMaze creates the classic Pac-Man maze.
func LoadClassicMaze() *Maze {
	m := NewMaze(MazeWidth, MazeHeight)
	
	for y := 0; y < MazeHeight; y++ {
		for x := 0; x < MazeWidth; x++ {
			m.Tiles[y][x] = classicMazeData[y][x]
		}
	}
	
	m.DotsRemaining = m.CountDots()
	m.TotalDots = m.DotsRemaining
	
	return m
}

